(defn- generate-random-key
  []
  (-> (bn/random-bytes 64)
      (bc/bytes->b64-str true)))

(defn- get-all-props
  [conn]
  (->> (db/query conn :server-prop {:preload true})
       (filter #(not= "secret-key" (:id %)))
       (map (fn [row]
              [(keyword (:id row))
               (db/decode-transit-pgobject (:content row))]))
       (into {})))

(defn- handle-instance-id
  [instance-id conn]
  (or instance-id
      (let [instance-id (uuid/random)]
        (try
          (db/insert! conn :server-prop
                      {:id "instance-id"
                       :preload true
                       :content (db/tjson instance-id)})
          (catch Throwable cause
            (l/warn :hint "unable to persist instance-id"
                    :instance-id instance-id
                    :cause cause)))
        instance-id)))

(def sql:add-prop
  "INSERT INTO server_prop (id, content, preload)
   VALUES (?, ?, ?)
       ON CONFLICT (id)
       DO UPDATE SET content=?, preload=?")

(def sql:insert-secret-key
  "INSERT INTO server_prop (id, content, preload)
   VALUES ('secret-key', ?, true)
   ON CONFLICT (id) DO NOTHING")

(defn- get-stored-secret-key
  [conn]
  (some-> (db/get* conn :server-prop {:id "secret-key"})
          (:content)
          (db/decode-transit-pgobject)))

(defn- persist-secret-key
  [conn key upsert?]
  (let [content (db/tjson key)]
    (if upsert?
      (db/exec-one! conn [sql:add-prop "secret-key" content true content true])
      (db/exec-one! conn [sql:insert-secret-key content]))))

(defn resolve-secret-key
  "Returns the master secret, persisting it in `server_prop` when possible.

  An explicit key wins and is upserted. Otherwise the stored value is reused,
  or a new one is generated and inserted with `ON CONFLICT DO NOTHING` so two
  replicas starting at the same time end up with the same value. A database
  that refuses the write (read-only) falls back to the in-memory key."
  [conn key]
  (if key
    (do
      (try
        (persist-secret-key conn key true)
        (catch Throwable cause
          (l/warn :hint "unable to persist secret-key"
                  :cause cause)))
      key)
    (or (get-stored-secret-key conn)
        (let [secret (generate-random-key)]
          (try
            (persist-secret-key conn secret false)
            (l/warn :hint "using autogenerated secret-key persisted in the database")
            (catch Throwable cause
              (l/warn :hint "unable to persist autogenerated secret-key; it will change on restart"
                      :cause cause)))
          (or (get-stored-secret-key conn) secret)))))

(defn get-prop
  ([system prop] (get-prop system prop nil))
  ([system prop default]
   (let [prop (d/name prop)]
     (db/run! system (fn [{:keys [::db/conn]}]
                       (or (db/get* conn :server-prop {:id prop})
                           default))))))

(defn set-prop!
  [system prop value]
  (let [value (db/tjson value)
        prop  (d/name prop)]
    (db/run! system (fn [{:keys [::db/conn]}]
                      (db/exec-one! conn [sql:add-prop prop value false value false])))))

(defmethod ig/assert-key ::props
  [_ params]
  (assert (db/pool? (::db/pool params)) "expected valid database pool"))

(defmethod ig/init-key ::props
  [_ {:keys [::key] :as cfg}]
  (audit/submit cfg {:type "trigger"
                     :name "instance-start"
                     :props {:version (:full cf/version)
                             :flags (mapv name cf/flags)
                             :public-uri (str (cf/get :public-uri))}})

  (db/tx-run! cfg (fn [{:keys [::db/conn]}]
                    (db/xact-lock! conn 0)
                    (let [secret (resolve-secret-key conn key)]
                      (-> (get-all-props conn)
                          (assoc :secret-key secret)
                          (assoc :tokens-key (keys/derive secret :salt "tokens"))
                          (update :instance-id handle-instance-id conn))))))

(defmethod ig/init-key ::shared-keys
  [_ {:keys [::props] :as cfg}]
  (let [secret (get props :secret-key)]
    (reduce (fn [keys id]
              (let [key (or (get cfg id)
                            (-> (keys/derive secret :salt (name id))
                                (bc/bytes->b64-str true)))]
                (if (or (str/empty? key)
                        (str/blank? key))
                  (do
                    (l/wrn :id (name id) :hint "key is disabled because empty string found")
                    keys)
                  (do
                    (l/inf :id (name id) :hint "key initialized" :key (d/obfuscate-string key))
                    (assoc keys id key)))))
            {}
            [:exporter
             :admin-console
             :nexus
             :media-processor])))

(sm/register! ::props [:map-of :keyword ::sm/any])
(sm/register! ::shared-keys [:map-of :keyword ::sm/text])

