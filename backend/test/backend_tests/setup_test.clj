(ns backend-tests.setup-test
  (:require
   [app.db :as db]
   [app.db :as-alias db]
   [app.setup :as setup]
   [backend-tests.helpers :as th]
   [clojure.test :as t]))

(t/use-fixtures :once th/state-init)
(t/use-fixtures :each th/database-reset)

(defn- resolve-secret-key
  [key]
  (db/tx-run! th/*system*
              (fn [{:keys [::db/conn]}]
                (setup/resolve-secret-key conn key))))

(defn- get-stored-secret-key
  []
  (db/tx-run! th/*system*
              (fn [{:keys [::db/conn]}]
                (some-> (db/get* conn :server-prop {:id "secret-key"})
                        (:content)
                        (db/decode-transit-pgobject)))))

(t/deftest autogenerated-secret-key-is-persisted
  (let [first  (resolve-secret-key nil)
        second (resolve-secret-key nil)]
    (t/testing "an autogenerated key is a non-empty string"
      (t/is (and (string? first) (seq first))))
    (t/testing "a later initialization reuses the stored key"
      (t/is (= first second)))
    (t/testing "the key is stored in server_prop"
      (t/is (= first (get-stored-secret-key))))))

(t/deftest configured-secret-key-overrides-the-stored-one
  (let [initial (resolve-secret-key nil)]
    (t/is (= "explicit-secret" (resolve-secret-key "explicit-secret")))
    (t/testing "the configured value replaces the stored row"
      (t/is (= "explicit-secret" (get-stored-secret-key)))
      (t/is (not= initial (get-stored-secret-key))))))

(t/deftest stored-secret-key-is-reused-without-a-configured-key
  (let [stored "stored-secret"]
    (resolve-secret-key stored)
    (t/is (= stored (resolve-secret-key nil)))))

(t/deftest read-only-database-falls-back-to-an-in-memory-key
  (with-redefs [db/exec-one! (fn [& _] (throw (Exception. "read only")))]
    (let [key (resolve-secret-key nil)]
      (t/testing "no exception escapes and a usable key is returned"
        (t/is (and (string? key) (seq key))))
      (t/testing "nothing is persisted"
        (t/is (nil? (get-stored-secret-key)))))))
